"""
Auto-update from GitHub releases — download, verify, stage; never switch mid-use.

Once a day (cfg "update_check_hours") the device reads the release manifest
published by tools/release.py, and if it names a newer version:

  1. checks the manifest's ECDSA signature against RELEASE_PUBKEY_B64 below —
     the code ends up running as root, and the repo is public;
  2. downloads the tarball and checks its size and SHA-256 (both signed);
  3. unpacks it into /root/isora-releases/.staging-<v>/, refusing anything
     that is not a plain file inside that folder, fsyncs it, and renames the
     folder to /root/isora-releases/<v>/ — one atomic step;
  4. writes `pending`. Nothing that is running has changed yet.

The switch itself belongs to /etc/isora/release.py, run by the app's init
script before the app starts: at the next boot, or sooner when this module
sees the device sitting in idle mode, silent, for _IDLE_BEFORE_SWITCH_S and
restarts the app. A release then runs on TRIAL until confirm_when_healthy()
vouches for it; one that keeps failing is rolled back and never retried.

Power can fail at any point: until step 3's rename only hidden staging files
exist, and every later step is a rename too (see system/release.py).

Without the boot helper installed (`tools/run.py --autostart` puts it in
/etc/isora/) this module does nothing at all — there would be no way back
from a bad release.
"""

import base64
import hashlib
import json
import os
import random
import shutil
import subprocess
import tarfile
import threading
import time
import urllib.request

from system import release as rel
from utils import release_sig

# Generated by `python tools/release.py keygen`; the private half is kept off
# the repo. Changing it means every unit needs one deploy to trust the new key.
RELEASE_PUBKEY_B64 = "BO5jdO+lURWIZ8n9rkI241ScmejaUppIQ41GecaVVp2zRR5H4AufquG/r5iic2RMMv+5OzO0jK/BLM7zCbuOXig="

# GitHub's "latest release" redirect: no API call, so no 60-requests-per-hour
# limit — which a carrier NAT can share between many phones.
MANIFEST_URL = "https://github.com/kutilz/isora/releases/latest/download/isora-device.json"

BOOT_HELPER = "/etc/isora/release.py"
APP_INIT = "/etc/init.d/S26isoraapp"

# The device boots at the epoch and NTP fixes the clock some time later; TLS
# certificate checks fail until then, and "last checked" would be nonsense.
_SANE_EPOCH = 1767225600            # 2026-01-01

_MANIFEST_MAX = 16 * 1024
_TARBALL_MAX = 30 * 1024 * 1024
_UNPACKED_MAX = 80 * 1024 * 1024
_MAX_MEMBERS = 5000
_FREE_MARGIN = 20 * 1024 * 1024

_TICK_S = 30.0
_FIRST_CHECK_S = (180.0, 480.0)     # after boot: let the app settle first
_RETRY_S = 3600.0                   # after a network / server error
_CLOCK_RETRY_S = 300.0
# Switching restarts the app (~20 s without obstacle detection), so only when
# nobody can be relying on it: idle mode, nothing being said, for this long.
_IDLE_BEFORE_SWITCH_S = 600.0
_EVENT_CHECK_S = 900.0

_APP_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


class UpdateError(Exception):
    pass


def current_version(app_dir: str = _APP_DIR) -> str:
    return rel.read_version(app_dir)


def check_manifest(m, pubkey_b64: str = None) -> dict:
    """Validate shape + signature. Raises UpdateError; returns the manifest."""
    if not isinstance(m, dict) or m.get("format") != 1:
        raise UpdateError("unknown manifest format")
    ver, url, size, digest, sig = (m.get("version"), m.get("url"), m.get("size"),
                                   m.get("sha256"), m.get("sig"))
    if not isinstance(ver, str) or not rel.safe_version(ver):
        raise UpdateError("bad version %r" % (ver,))
    if not isinstance(url, str) or not url.startswith("https://"):
        raise UpdateError("download URL must be https")
    if not isinstance(size, int) or not 0 < size <= _TARBALL_MAX:
        raise UpdateError("bad size %r" % (size,))
    if not isinstance(digest, str) or len(digest) != 64 or \
            any(c not in "0123456789abcdef" for c in digest):
        raise UpdateError("bad sha256")
    try:
        raw_sig = base64.b64decode(sig or "", validate=True)
    except Exception:
        raise UpdateError("bad signature encoding")
    if not release_sig.verify(pubkey_b64 or RELEASE_PUBKEY_B64,
                              release_sig.release_message(ver, digest, size), raw_sig):
        raise UpdateError("signature does not verify")
    return m


def safe_extract(tar_path: str, dest: str) -> int:
    """Unpack plain files only, all inside `dest`, fsync'd. Returns file count."""
    os.makedirs(dest, exist_ok=True)
    count = total = 0
    dirs = {dest}
    with tarfile.open(tar_path, "r:gz") as tf:
        for m in tf:
            count += 1
            if count > _MAX_MEMBERS:
                raise UpdateError("too many files in package")
            name = m.name
            if name.startswith("/") or "\\" in name or ":" in name.split("/")[0]:
                raise UpdateError("absolute path in package: %r" % name)
            parts = [p for p in name.split("/") if p not in ("", ".")]
            if not parts or ".." in parts:
                raise UpdateError("path escapes the package: %r" % name)
            out = os.path.join(dest, *parts)
            if m.isdir():
                os.makedirs(out, exist_ok=True)
                dirs.add(out)
                continue
            if not m.isfile():
                raise UpdateError("not a plain file: %r" % name)
            total += m.size
            if total > _UNPACKED_MAX:
                raise UpdateError("package too large unpacked")
            parent = os.path.dirname(out)
            os.makedirs(parent, exist_ok=True)
            dirs.add(parent)
            src = tf.extractfile(m)
            with open(out, "wb") as f:
                shutil.copyfileobj(src, f)
                f.flush()
                os.fsync(f.fileno())
            os.chmod(out, 0o755 if m.mode & 0o111 else 0o644)
    for d in sorted(dirs, key=len, reverse=True):
        rel._fsync_dir(d)
    return count


def _urlopen(url: str, timeout: float):
    req = urllib.request.Request(url, headers={"User-Agent": "isora-device-updater"})
    return urllib.request.urlopen(req, timeout=timeout)


class Updater:

    def __init__(self, orchestrator, logger, layout=None, opener=None,
                 helper: str = BOOT_HELPER, app_init: str = APP_INIT,
                 app_dir: str = _APP_DIR, pubkey_b64: str = None,
                 clock=time.monotonic, wall=time.time):
        self.orch = orchestrator
        self.logger = logger
        self.L = layout or rel.Layout()
        self._open = opener or _urlopen
        self.helper = helper
        self.app_init = app_init
        self.app_dir = app_dir
        self.pubkey = pubkey_b64 or RELEASE_PUBKEY_B64
        self._clock = clock
        self._wall = wall
        self._idle_since = None
        self._stop = threading.Event()

    def stop(self):
        self._stop.set()

    # ─── config ───────────────────────────────────────────────────────────────

    @staticmethod
    def _cfg(key, default):
        try:
            from config import cfg
            return cfg.get(key, default)
        except Exception:
            return default

    def _interval_s(self) -> float:
        if self._cfg("event_mode", False) is True:
            # The person fixing things is remote during an event: a release they
            # publish must be on the unit by its next power cycle.
            return _EVENT_CHECK_S
        try:
            hours = float(self._cfg("update_check_hours", 24))
        except (TypeError, ValueError):
            hours = 24.0
        return max(1.0, hours) * 3600.0

    # ─── one check ────────────────────────────────────────────────────────────

    def check_once(self) -> str:
        """Fetch → verify → stage. Returns an outcome word; raises on errors."""
        if not self._cfg("auto_update", True):
            return "disabled"
        if self._cfg("event_mode", False) is True and not self._device_idle():
            # Mode PIMNAS: the download waits until nobody is using the device.
            # Staging is safe in idle; the switch still waits for the next boot.
            return "event-busy"
        if not os.path.isfile(self.helper):
            return "no-boot-helper"
        if self._wall() < _SANE_EPOCH:
            return "clock-not-set"

        with self._open(MANIFEST_URL, 20) as r:
            raw = r.read(_MANIFEST_MAX + 1)
        if len(raw) > _MANIFEST_MAX:
            raise UpdateError("manifest too large")
        try:
            m = check_manifest(json.loads(raw), self.pubkey)
        except ValueError:
            raise UpdateError("manifest is not JSON")
        self._note_checked()

        ver = m["version"]
        if not rel.is_newer(ver, current_version(self.app_dir)):
            return "up-to-date"
        if ver in rel.bad_versions(self.L):
            return "known-bad"
        os.makedirs(self.L.releases, exist_ok=True)
        target = self.L.release_dir(ver)
        if not rel.valid_release(target):
            self._stage(m, target)
        rel.request(self.L, ver)
        self.cleanup()
        self.logger.info("Update %s ready — switches at the next quiet moment" % ver,
                         module="Updater")
        return "staged"

    def _stage(self, m: dict, target: str):
        ver = m["version"]
        free = shutil.disk_usage(self.L.releases).free
        if free < m["size"] * 4 + _FREE_MARGIN:
            raise UpdateError("not enough space (%d MB free)" % (free // 2**20))
        dl = os.path.join(self.L.releases, ".dl-%s.tar.gz" % ver)
        staging = os.path.join(self.L.releases, ".staging-%s" % ver)
        try:
            h = hashlib.sha256()
            size = 0
            with self._open(m["url"], 60) as r, open(dl, "wb") as f:
                while True:
                    chunk = r.read(64 * 1024)
                    if not chunk:
                        break
                    size += len(chunk)
                    if size > m["size"]:
                        raise UpdateError("download larger than signed size")
                    h.update(chunk)
                    f.write(chunk)
                f.flush()
                os.fsync(f.fileno())
            if size != m["size"] or h.hexdigest() != m["sha256"]:
                raise UpdateError("download does not match the signed hash")
            shutil.rmtree(staging, ignore_errors=True)
            safe_extract(dl, staging)
            if rel.read_version(staging) != ver or not rel.valid_release(staging):
                raise UpdateError("package does not contain version %s" % ver)
            if os.path.lexists(target):
                shutil.rmtree(target)            # leftover that never became valid
            os.rename(staging, target)
            rel._fsync_dir(self.L.releases)
        finally:
            for path in (dl, staging):
                if os.path.isdir(path):
                    shutil.rmtree(path, ignore_errors=True)
                elif os.path.exists(path):
                    os.unlink(path)

    def _note_checked(self):
        try:
            os.makedirs(self.L.releases, exist_ok=True)
            rel.atomic_write(os.path.join(self.L.releases, "last_check"),
                             "%d\n" % int(self._wall()))
        except OSError:
            pass

    def cleanup(self):
        """Drop releases nobody can switch to any more, and crash leftovers."""
        keep = set()
        for p in (rel.current_target(self.L),
                  os.path.realpath(self.L.previous) if os.path.islink(self.L.previous) else None):
            if p:
                keep.add(os.path.realpath(p))
        pend = rel._read(self.L.pending).strip()
        if pend:
            keep.add(os.path.realpath(self.L.release_dir(pend)))
        try:
            names = os.listdir(self.L.releases)
        except OSError:
            return
        for name in names:
            path = self.L.release_dir(name)
            if name.startswith((".dl-", ".staging-")) or ".tmp-" in name:
                if os.path.isdir(path) and not os.path.islink(path):
                    shutil.rmtree(path, ignore_errors=True)
                else:
                    try:
                        os.unlink(path)
                    except OSError:
                        pass
            elif (rel.parse_version(name) is not None and os.path.isdir(path)
                  and not os.path.islink(path) and os.path.realpath(path) not in keep):
                shutil.rmtree(path, ignore_errors=True)
                self.logger.info("Removed old release %s" % name, module="Updater")

    # ─── switching ────────────────────────────────────────────────────────────

    def _can_restart(self) -> bool:
        try:
            with open(self.app_init) as f:
                return "restart)" in f.read()
        except OSError:
            return False

    def _device_idle(self) -> bool:
        try:
            if self.orch.mode != "idle":
                return False
            am = getattr(self.orch, "audio_manager", None)
            return not (am is not None and am.current_text)
        except Exception:
            return False

    def maybe_switch(self) -> bool:
        """Restart into a staged release once the device has been quiet a while."""
        if not os.path.exists(self.L.pending) or not os.path.isfile(self.helper):
            self._idle_since = None
            return False
        if self._cfg("event_mode", False) is True:
            # A demo pauses in idle between presenters; that must never be read
            # as "nobody is using it" and turned into a restart on stage.
            self._idle_since = None
            return False
        if not self._can_restart() or not self._device_idle():
            self._idle_since = None
            return False
        now = self._clock()
        if self._idle_since is None:
            self._idle_since = now
            return False
        if now - self._idle_since < _IDLE_BEFORE_SWITCH_S:
            return False
        self.logger.info("Device idle — restarting into the staged update",
                         module="Updater")
        # Own session: the restart stops THIS process, and must outlive it.
        subprocess.Popen([self.app_init, "restart"], stdin=subprocess.DEVNULL,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                         close_fds=True, start_new_session=True)
        self._idle_since = None
        return True

    # ─── loop ─────────────────────────────────────────────────────────────────

    def _first_check_at(self) -> float:
        interval = self._interval_s()
        try:
            last = float(rel._read(os.path.join(self.L.releases, "last_check")).strip())
        except ValueError:
            last = 0.0
        age = self._wall() - last
        if self._wall() >= _SANE_EPOCH and last and 0 <= age < interval:
            return self._clock() + (interval - age)
        return self._clock() + random.uniform(*_FIRST_CHECK_S)

    def run(self):
        next_check = self._first_check_at()
        while not self._stop.wait(_TICK_S):
            try:
                self.maybe_switch()
            except Exception as e:
                self.logger.warn("Update switch failed: %s" % e, module="Updater")
            if self._clock() < next_check:
                continue
            try:
                outcome = self.check_once()
                self.logger.info("Update check: %s" % outcome, module="Updater")
                delay = _CLOCK_RETRY_S if outcome == "clock-not-set" else self._interval_s()
            except Exception as e:
                self.logger.warn("Update check failed: %s" % e, module="Updater")
                delay = _RETRY_S
            next_check = self._clock() + delay * random.uniform(0.9, 1.1)


def confirm_when_healthy(orchestrator, logger, layout=None, app_dir: str = _APP_DIR,
                         settle_s: float = 30.0, window_s: float = 120.0,
                         sleep=time.sleep, clock=time.monotonic) -> bool:
    """Vouch for a release on trial once the AI loop has been beating steadily.

    The init script's guard rolls the release back if this has not happened
    240 s after the app was spawned (tools/run.py APP_INIT_SCRIPT). Counting
    from boot-ready (~10 s after spawn), settle + window ends near 160 s, which
    leaves room for a slow start on a busy unit.
    """
    L = layout or rel.Layout()
    ver = current_version(app_dir)
    trial_ver, _ = rel.read_trial(L)
    if not trial_ver or trial_ver != ver:
        return False
    sleep(settle_s)
    end = clock() + window_s
    while clock() < end:
        try:
            healthy = orchestrator.loop_healthy(45.0)
        except Exception:
            healthy = False
        if healthy:
            rel.confirm(L, ver)
            logger.ok("Release %s confirmed healthy" % ver, module="Updater")
            return True
        sleep(10.0)
    logger.warn("Release %s not confirmed — it will be rolled back" % ver,
                module="Updater")
    return False
